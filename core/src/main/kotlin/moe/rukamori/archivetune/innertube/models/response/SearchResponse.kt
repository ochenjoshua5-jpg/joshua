package com.ochenjoshua.ojmusicplayer.innertube.models.response

import kotlinx.serialization.Serializable
import com.ochenjoshua.ojmusicplayer.innertube.models.Continuation
import com.ochenjoshua.ojmusicplayer.innertube.models.ContinuationItemRenderer
import com.ochenjoshua.ojmusicplayer.innertube.models.MusicResponsiveListItemRenderer
import com.ochenjoshua.ojmusicplayer.innertube.models.Tabs

@Serializable
data class SearchResponse(
    val contents: Contents?,
    val continuationContents: ContinuationContents?,
) {
    @Serializable
    data class Contents(
        val tabbedSearchResultsRenderer: Tabs?,
    )

    @Serializable
    data class ContinuationContents(
        val musicShelfContinuation: MusicShelfContinuation,
    ) {
        @Serializable
        data class MusicShelfContinuation(
            val contents: List<Content>,
            val continuations: List<Continuation>?,
        ) {
            @Serializable
            data class Content(
                val musicResponsiveListItemRenderer: MusicResponsiveListItemRenderer? = null,
                val continuationItemRenderer: ContinuationItemRenderer? = null,
            )
        }
    }
}
