package com.ochenjoshua.ojmusicplayer.innertube.models.response

import kotlinx.serialization.Serializable
import com.ochenjoshua.ojmusicplayer.innertube.models.NavigationEndpoint
import com.ochenjoshua.ojmusicplayer.innertube.models.PlaylistPanelRenderer
import com.ochenjoshua.ojmusicplayer.innertube.models.Tabs
import com.ochenjoshua.ojmusicplayer.innertube.models.YouTubeDataPage

@Serializable
data class NextResponse(
    val contents: Contents,
    val continuationContents: ContinuationContents?,
    val currentVideoEndpoint: NavigationEndpoint?,
) {
    @Serializable
    data class Contents(
        val singleColumnMusicWatchNextResultsRenderer: SingleColumnMusicWatchNextResultsRenderer?,
        val twoColumnWatchNextResults: YouTubeDataPage.Contents.TwoColumnWatchNextResults?,
    ) {
        @Serializable
        data class SingleColumnMusicWatchNextResultsRenderer(
            val tabbedRenderer: TabbedRenderer?,
        ) {
            @Serializable
            data class TabbedRenderer(
                val watchNextTabbedResultsRenderer: WatchNextTabbedResultsRenderer?,
            ) {
                @Serializable
                data class WatchNextTabbedResultsRenderer(
                    val tabs: List<Tabs.Tab>,
                )
            }
        }
    }

    @Serializable
    data class ContinuationContents(
        val playlistPanelContinuation: PlaylistPanelRenderer,
    )
}
